import 'dart:io';
import 'package:bloom_js_native/bloom_js_native.dart';
import 'package:bloom_js_native/ssg.dart';
import 'package:test/test.dart';

void main() {
  group('generateStaticSite', () {
    late Directory tempDir;
    late Directory webDir;
    late Directory distDir;

    setUp(() {
      tempDir = Directory.systemTemp.createTempSync('bloom_ssg_test_');
      webDir = Directory('${tempDir.path}/web')..createSync(recursive: true);
      distDir = Directory('${tempDir.path}/dist');
    });

    tearDown(() {
      if (tempDir.existsSync()) {
        try {
          tempDir.deleteSync(recursive: true);
        } catch (_) {}
      }
    });

    test('throws StateError when web/main.js is missing', () async {
      expect(
        () => generateStaticSite(
          pages: {'/': () => Div(text: 'Hello')},
          outDir: distDir.path,
          webDir: webDir.path,
        ),
        throwsA(isA<StateError>().having(
          (e) => e.message,
          'message',
          contains('Run `bloom js build` first'),
        )),
      );
    });

    test(
        'writes index.html and about/index.html, copies web assets except index.html and *.deps',
        () async {
      // 1. Create web assets
      File('${webDir.path}/main.js')
          .writeAsStringSync('console.log("main.js");');
      File('${webDir.path}/main.js.deps')
          .writeAsStringSync('dummy deps content');
      File('${webDir.path}/index.html')
          .writeAsStringSync('<html>dev index</html>');
      File('${webDir.path}/style.css').writeAsStringSync('body { margin: 0; }');
      final nestedAssetDir = Directory('${webDir.path}/assets')
        ..createSync(recursive: true);
      File('${nestedAssetDir.path}/logo.svg').writeAsStringSync('<svg></svg>');

      // 2. Create bloom.yaml with an npm package
      final bloomYaml = File('${tempDir.path}/bloom.yaml');
      bloomYaml.writeAsStringSync('''
name: ssg_test_project
npm_packages:
  canvas-confetti:
    version: 1.9.4
    vendor_file: web/vendor/canvas-confetti.min.js
''');
      final vendorDir = Directory('${webDir.path}/vendor')
        ..createSync(recursive: true);
      File('${vendorDir.path}/canvas-confetti.min.js')
          .writeAsStringSync('// confetti code');

      final result = await generateStaticSite(
        pages: {
          '/': () => H1(text: 'Home Page'),
          '/about': () => P(text: 'About Page'),
        },
        outDir: distDir.path,
        webDir: webDir.path,
        bloomYamlPath: bloomYaml.path,
        title: 'Default Title',
        titleFor: (path) => path == '/about' ? 'About Us' : 'Default Title',
      );

      expect(result.pageCount, 2);
      expect(File('${distDir.path}/index.html').existsSync(), isTrue);
      expect(File('${distDir.path}/about/index.html').existsSync(), isTrue);

      // Verify asset copying
      expect(File('${distDir.path}/main.js').existsSync(), isTrue);
      expect(File('${distDir.path}/style.css').existsSync(), isTrue);
      expect(File('${distDir.path}/assets/logo.svg').existsSync(), isTrue);
      expect(File('${distDir.path}/vendor/canvas-confetti.min.js').existsSync(),
          isTrue);

      // Verify ignored files
      expect(File('${distDir.path}/main.js.deps').existsSync(), isFalse);

      // Check contents of dist/index.html
      final homeHtml = File('${distDir.path}/index.html').readAsStringSync();
      expect(homeHtml, isNot(contains('<html>dev index</html>')));
      expect(homeHtml, contains('<title>Default Title</title>'));
      expect(homeHtml, contains('<h1>Home Page</h1>'));
      expect(homeHtml, contains('<div id="app">'));

      // Check script tag ordering: caller head -> npm head -> main.js with defer
      expect(homeHtml, contains('<script type="importmap">'));
      expect(
          homeHtml,
          contains(
              '// AUTO-GENERATED by bloom_cli — bridges vendored ESM packages onto'));
      expect(homeHtml, contains('<script src="/main.js" defer=""></script>'));

      final importmapIdx = homeHtml.indexOf('<script type="importmap">');
      final bootstrapIdx = homeHtml.indexOf('// AUTO-GENERATED by bloom_cli');
      final mainScriptIdx =
          homeHtml.indexOf('<script src="/main.js" defer=""></script>');
      expect(importmapIdx, lessThan(bootstrapIdx));
      expect(bootstrapIdx, lessThan(mainScriptIdx));

      // Check contents of dist/about/index.html
      final aboutHtml =
          File('${distDir.path}/about/index.html').readAsStringSync();
      expect(aboutHtml, contains('<title>About Us</title>'));
      expect(aboutHtml, contains('<p>About Page</p>'));
      expect(aboutHtml, contains('<script src="/main.js" defer=""></script>'));
    });
  });
}
